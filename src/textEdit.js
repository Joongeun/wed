// In-place text replacement for static mode.
//
// The browser sends the element's source location, its text before the edit, and the
// new text. The edit is written straight into the file only when it is unambiguous:
// the element must contain plain text and nothing else, and its current text on disk
// must match what the browser showed. Anything else is refused with a reason, and the
// overlay falls back to queuing the change as a note for Claude.

import fs from 'node:fs';
import path from 'node:path';
import { parseWithLocations, findElementAt, parseSrc } from './annotate.js';

export const norm = (s) => String(s).replace(/\s+/g, ' ').trim();

export function escapeText(s) {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

/** Pure function: returns { ok, html } or { ok: false, reason }. */
export function replaceTextInHtml(html, line, col, oldText, newText) {
  const doc = parseWithLocations(html);
  const el = findElementAt(doc, line, col);
  if (!el) return { ok: false, reason: 'element not found at that line; the file changed since the page loaded' };
  const loc = el.sourceCodeLocation;
  if (!loc.endTag) return { ok: false, reason: 'element has no explicit closing tag' };
  const kids = el.childNodes || [];
  if (kids.length === 0) {
    if (norm(oldText) !== '') return { ok: false, reason: 'element is empty on disk' };
  } else if (!kids.every((k) => k.nodeName === '#text')) {
    return { ok: false, reason: 'element mixes text with other tags' };
  }
  const current = kids.map((k) => k.value).join('');
  if (norm(current) !== norm(oldText)) {
    return { ok: false, reason: 'text on disk differs from the page; it was probably generated by a script' };
  }
  if (/\{\{|\{%|<%|<\?/.test(html.slice(loc.startTag.endOffset, loc.endTag.startOffset))) {
    return { ok: false, reason: 'text contains template syntax' };
  }
  const start = loc.startTag.endOffset;
  const end = loc.endTag.startOffset;
  const inner = html.slice(start, end);
  const lead = /^\s*/.exec(inner)[0];
  const trail = /\s*$/.exec(inner)[0];
  // Keep the original indentation around the text so the diff touches only the words.
  const replacement = inner.trim() === '' ? escapeText(newText) : lead + escapeText(newText.trim()) + trail;
  return { ok: true, html: html.slice(0, start) + replacement + html.slice(end), before: inner, after: replacement };
}

/** Apply an edit to a file under root. Refuses paths that escape root. */
export function applyTextEdit(root, src, oldText, newText) {
  const p = parseSrc(src);
  if (!p) return { ok: false, reason: 'no source location; proxy mode cannot edit files directly' };
  const abs = path.resolve(root, p.file);
  if (!abs.startsWith(path.resolve(root) + path.sep)) return { ok: false, reason: 'path outside project root' };
  let html;
  try {
    html = fs.readFileSync(abs, 'utf8');
  } catch {
    return { ok: false, reason: `cannot read ${p.file}` };
  }
  const r = replaceTextInHtml(html, p.line, p.col, oldText, newText);
  if (!r.ok) return r;
  fs.writeFileSync(abs, r.html);
  return { ok: true, file: p.file, line: p.line, before: r.before, after: r.after };
}
